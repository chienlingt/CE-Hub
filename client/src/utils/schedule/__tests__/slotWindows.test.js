import {
  SLOT_WINDOWS, clockToMinutes, minutesToClock, getSlotWindowId,
  getSlotWindow, windowLabel, compareWindows, slotDurationMinutes,
} from '../slotWindows';

describe('clockToMinutes', () => {
  it.each([
    ['00:00', 0],
    ['08:00', 480],
    ['13:00', 780],
    ['19:00', 1140],
    ['23:59', 1439],
    ['9:30', 570],       // single-digit hour, as some records carry
    ['08:00:00', 480],   // seconds tolerated
  ])('parses %s', (input, expected) => {
    expect(clockToMinutes(input)).toBe(expected);
  });

  it.each([null, undefined, '', 'noon', '25:00', '08:99', 480, {}])(
    'returns null for %p', (input) => {
      expect(clockToMinutes(input)).toBeNull();
    },
  );
});

describe('minutesToClock', () => {
  it('round-trips', () => {
    expect(minutesToClock(480)).toBe('08:00');
    expect(minutesToClock(1140)).toBe('19:00');
  });

  it('clamps out-of-range values into a single day', () => {
    expect(minutesToClock(-10)).toBe('00:00');
    expect(minutesToClock(99999)).toBe('23:59');
  });

  it('returns empty for non-numbers', () => {
    expect(minutesToClock(NaN)).toBe('');
    expect(minutesToClock(undefined)).toBe('');
  });
});

describe('getSlotWindowId', () => {
  // The regression this module exists for. utils/driverOrderFilters.js matched
  // against windows starting at 09:00 and returned 'other' below that, so every
  // 08:00 slot generated by server/services/scheduler.js:310 was mis-bucketed.
  it('classifies the 08:00 slots the engine actually generates as AM', () => {
    expect(getSlotWindowId('08:00')).toBe('am');
  });

  it.each([
    ['00:00', 'am'],
    ['08:00', 'am'],
    ['09:00', 'am'],
    ['10:00', 'am'],
    ['11:59', 'am'],
    ['13:00', 'pm'],
    ['14:00', 'pm'],
    ['18:59', 'pm'],
    ['19:00', 'night'],
    ['21:00', 'night'],
  ])('maps %s to %s', (clock, expected) => {
    expect(getSlotWindowId(clock)).toBe(expected);
  });

  // The windows don't tile the day: AM ends 12:00 but PM starts 13:00. The rule
  // is "the latest window that has already started", so the gap reads as AM.
  it('classifies the 12:00–13:00 gap as AM, by the latest-started rule', () => {
    expect(getSlotWindowId('12:00')).toBe('am');
    expect(getSlotWindowId('12:59')).toBe('am');
  });

  it('accepts a raw API slot record (snake_case)', () => {
    expect(getSlotWindowId({ time_window_start: '08:00' })).toBe('am');
  });

  it('accepts a normalized slot record', () => {
    expect(getSlotWindowId({ start: '14:00' })).toBe('pm');
  });

  it('prefers the normalized field when both are present', () => {
    expect(getSlotWindowId({ start: '20:00', time_window_start: '08:00' })).toBe('night');
  });

  it('returns other when there is nothing to classify', () => {
    expect(getSlotWindowId(null)).toBe('other');
    expect(getSlotWindowId({})).toBe('other');
    expect(getSlotWindowId({ start: 'whenever' })).toBe('other');
  });

  // The three sources disagree on start times, so classification must be
  // threshold-based. These are the proposal's windows, not the engine's.
  it('still classifies the design proposal’s different windows correctly', () => {
    expect(getSlotWindowId('10:00')).toBe('am');
    expect(getSlotWindowId('14:00')).toBe('pm');
    expect(getSlotWindowId('18:00')).toBe('pm');
  });

  it('classifies seedDemo.js’s windows correctly', () => {
    expect(getSlotWindowId('09:00')).toBe('am');
    expect(getSlotWindowId('14:00')).toBe('pm');
  });
});

describe('getSlotWindow / windowLabel', () => {
  it('returns the descriptor', () => {
    expect(getSlotWindow('08:00')).toMatchObject({ id: 'am', label: 'AM' });
  });

  it('returns null when unclassifiable', () => {
    expect(getSlotWindow('bogus')).toBeNull();
  });

  it('labels known windows and falls back for unknown', () => {
    expect(windowLabel('am')).toBe('AM');
    expect(windowLabel('night')).toBe('NIGHT');
    expect(windowLabel('other')).toBe('—');
  });
});

describe('compareWindows', () => {
  it('orders AM, PM, NIGHT then unknowns', () => {
    const sorted = ['night', 'other', 'am', 'pm'].sort(compareWindows);
    expect(sorted).toEqual(['am', 'pm', 'night', 'other']);
  });
});

describe('slotDurationMinutes', () => {
  it('measures the window', () => {
    expect(slotDurationMinutes({ start: '08:00', end: '12:00' })).toBe(240);
    expect(slotDurationMinutes({ time_window_start: '13:00', time_window_end: '19:00' })).toBe(360);
  });

  it('never returns a negative duration', () => {
    expect(slotDurationMinutes({ start: '19:00', end: '08:00' })).toBe(0);
  });

  it('returns null when either end is unparseable', () => {
    expect(slotDurationMinutes({ start: '08:00' })).toBeNull();
    expect(slotDurationMinutes(null)).toBeNull();
  });
});

describe('SLOT_WINDOWS', () => {
  it('matches the windows the engine generates', () => {
    expect(SLOT_WINDOWS.map(w => [w.start, w.end])).toEqual([
      ['08:00', '12:00'],
      ['13:00', '19:00'],
      ['19:00', '21:00'],
    ]);
  });
});
